#!/usr/bin/env python3
"""Builds src/host/overlay_ui_font.h: the proportional fonts of the in-game menus, for every
language the F10 menu speaks (src/host/menu_i18n.h).

Helia's Dream's look (the launcher's) in the engine's overlay: Manrope for text, in a regular
and a bold weight, and Cormorant Garamond for titles, rasterised once into one 8-bit atlas with
each glyph's box, offset and advance. The overlay draws them scaled, linearly filtered, so they
are rendered large here (body 34 px, titles 68 px). The monospace atlas (overlay_font.h) is
copied into the top-left corner, so one texture and one descriptor serve every font.

Fonts: launcher/HeliasDream/Assets/Fonts (SIL Open Font License 1.1).

    tools/make_overlay_fonts.py            # writes src/host/overlay_ui_font.h
"""
import os
import re
import sys

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONTS = os.path.join(ROOT, "launcher", "HeliasDream", "Assets", "Fonts")
MONO = os.path.join(ROOT, "src", "host", "overlay_font.h")
OUT = os.path.join(ROOT, "src", "host", "overlay_ui_font.h")

ATLAS_W = 1024
# ASCII, Latin-1 and Latin Extended-A (the F10 menu's Western and Central European languages,
# Turkish), Cyrillic (Russian), and the punctuation translations use. Sorted: the overlay finds a
# code by binary search (glyph_index).
CODES = sorted(set(list(range(32, 127)) + list(range(0xA0, 0x180)) + list(range(0x400, 0x460)) +
                   [0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x201E, 0x2026, 0x2022, 0x2192]))
PAD = 2
# name, file, pixel size, variable-font weight
FACES = [
    ("Body", "Manrope.ttf", 34, 500),
    ("Bold", "Manrope.ttf", 34, 700),
    ("Title", "CormorantGaramond.ttf", 68, 600),
]


def mono_atlas():
    text = open(MONO).read()
    w = int(re.search(r"kAtlasW = (\d+)", text).group(1))
    h = int(re.search(r"kAtlasH = (\d+)", text).group(1))
    body = text[text.index("kAtlas[] = {") :]
    data = [int(v) for v in re.findall(r"\d+", body[: body.index("};")])]
    assert len(data) == w * h, (len(data), w, h)
    img = Image.new("L", (w, h))
    img.putdata(data)
    return img


def load(file, size, weight):
    font = ImageFont.truetype(os.path.join(FONTS, file), size)
    try:
        font.set_variation_by_axes([weight])
    except (OSError, AttributeError):
        pass
    return font


def main():
    mono = mono_atlas()
    rows = []  # (face, glyphs)
    x, y, row_h = 0, mono.height + PAD, 0
    placed = {}
    images = []
    for name, file, size, weight in FACES:
        font = load(file, size, weight)
        ascent, descent = font.getmetrics()
        glyphs = []
        for code in CODES:
            ch = chr(code)
            advance = font.getlength(ch)
            box = font.getbbox(ch)  # relative to the pen at the line's top (ascender origin)
            gw, gh = max(0, box[2] - box[0]), max(0, box[3] - box[1])
            if gw == 0 or gh == 0:
                glyphs.append((0, 0, 0, 0, 0, 0, advance))
                continue
            if x + gw + PAD > ATLAS_W:
                x, y, row_h = 0, y + row_h + PAD, 0
            img = Image.new("L", (gw, gh))
            ImageDraw.Draw(img).text((-box[0], -box[1]), ch, font=font, fill=255)
            images.append((img, x, y))
            glyphs.append((x, y, gw, gh, box[0], box[1], advance))
            x += gw + PAD
            row_h = max(row_h, gh)
        rows.append((name, size, ascent, descent, glyphs))
        x, y, row_h = 0, y + row_h + PAD, 0

    height = y + 4
    height = (height + 7) // 8 * 8
    atlas = Image.new("L", (ATLAS_W, height))
    atlas.paste(mono, (0, 0))
    for img, gx, gy in images:
        atlas.paste(img, (gx, gy))
    # A fully lit texel for plain shapes, kept where the mono atlas had it.
    solid = (mono.width - 2, mono.height - 2)
    assert atlas.getpixel(solid) == 255

    out = []
    out.append("// Generated by tools/make_overlay_fonts.py - do not edit.")
    out.append("// Manrope (regular and bold) and Cormorant Garamond, SIL Open Font License 1.1,")
    out.append("// with the monospace atlas (overlay_font.h) in the top-left corner.")
    out.append("#pragma once")
    out.append("#include <cstdint>")
    out.append("namespace overlay_ui_font {")
    out.append(f"constexpr int kAtlasW = {ATLAS_W}, kAtlasH = {height};")
    out.append(f"constexpr int kSolidX = {solid[0]}, kSolidY = {solid[1]};")
    out.append(f"constexpr int kGlyphs = {len(CODES)};")
    out.append("// The code points the faces have, ascending; a glyph's index is its code's here.")
    out.append("constexpr std::uint16_t kCodes[kGlyphs] = {" + ", ".join(str(c) for c in CODES) + "};")
    out.append("struct Glyph { std::uint16_t x, y, w, h; std::int16_t ox, oy; float advance; };")
    out.append("struct Face { int size, ascent, descent; Glyph glyphs[kGlyphs]; };")
    for name, size, ascent, descent, glyphs in rows:
        out.append(f"constexpr Face k{name} = {{{size}, {ascent}, {descent}, {{")
        for g in glyphs:
            out.append("    {%d, %d, %d, %d, %d, %d, %.3ff}," % g)
        out.append("}};")
    out.append("const std::uint8_t kAtlas[] = {")
    data = list(atlas.getdata())
    for i in range(0, len(data), 48):
        out.append("    " + ",".join(str(v) for v in data[i : i + 48]) + ",")
    out.append("};")
    out.append("// The index of a code point's glyph, or -1 when the faces have none.")
    out.append("inline int glyph_index(unsigned code) {")
    out.append("    int lo = 0, hi = kGlyphs - 1;")
    out.append("    while (lo <= hi) {")
    out.append("        const int mid = (lo + hi) / 2;")
    out.append("        if (kCodes[mid] == code) return mid;")
    out.append("        if (kCodes[mid] < code) lo = mid + 1; else hi = mid - 1;")
    out.append("    }")
    out.append("    return -1;")
    out.append("}")
    out.append("}  // namespace overlay_ui_font")
    open(OUT, "w").write("\n".join(out) + "\n")
    print(f"{OUT}: {ATLAS_W}x{height}")


if __name__ == "__main__":
    sys.exit(main())
